for gen_key, target in GENERIC_MAP.items():
    if gen_key not in _NORMALIZED_LOOKUP:
        _NORMALIZED_LOOKUP[gen_key] = target


def get_canonical_crop_name(crop_name: Optional[str]) -> str:
    """Resolve an English, Arabic, or alias crop name to its canonical 53-crop English name."""
    if not crop_name:
        return ""
    clean = _clean_str(crop_name)
    return _NORMALIZED_LOOKUP.get(clean, crop_name.strip())


def get_crop_entry(crop_name: str) -> Optional[CropRegistryEntry]:
    """Retrieve full CropRegistryEntry for any recognized crop string."""
    canonical = get_canonical_crop_name(crop_name)
    return CROP_REGISTRY.get(canonical)


def get_arabic_crop_name(crop_name: str) -> str:
    """Retrieve Arabic display name for any crop string."""
    entry = get_crop_entry(crop_name)
    if entry:
        return entry.canonical_name_ar
    return crop_name


def get_allowed_seasons(crop_name: str) -> List[str]:
    """Retrieve allowed agricultural seasons for any crop string."""
    entry = get_crop_entry(crop_name)
    if entry:
        return list(entry.allowed_seasons)
    return ["Winter", "Summer", "Nili"]


def is_crop_allowed_in_season(crop_name: str, season_name: str) -> bool:
    """Check if crop is agronomically permissible in specified season."""
    seasons = get_allowed_seasons(crop_name)
    clean_season = season_name.strip().capitalize()
    return (
        clean_season in seasons
        or "Perennial" in seasons
        or "All" in seasons
    )


def get_crop_water_key(crop_name: str) -> str:
    """Retrieve corresponding water requirement database key."""
    entry = get_crop_entry(crop_name)
    if entry:
        return entry.water_key
    return crop_name


def get_crop_ecocrop_name(crop_name: str) -> str:
    """Retrieve corresponding EcoCrop database species name."""
    entry = get_crop_entry(crop_name)
    if entry:
        return entry.ecocrop_species
    return crop_name


def get_all_canonical_names() -> List[str]:
    """Return sorted list of all 53 canonical crop names."""
    return sorted(list(CROP_REGISTRY.keys()))


def get_all_crop_entries() -> List[CropRegistryEntry]:
    """Return list of all 53 CropRegistryEntry objects."""
    return list(CROP_REGISTRY.values())
