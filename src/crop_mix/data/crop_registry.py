# -----------------------------------------------------------------------------
# DYNAMIC LOOKUP INDEX (Resolves synonyms, Arabic names, plurals, spellings)
# -----------------------------------------------------------------------------
_NORMALIZED_LOOKUP: Dict[str, str] = {}

def _clean_str(text: str) -> str:
    """Normalize string by removing leading/trailing spaces and collapsing internal whitespace."""
    if not text:
        return ""
    return " ".join(str(text).strip().split()).lower()

for canonical_name, entry in CROP_REGISTRY.items():
    # Canonical English
    _NORMALIZED_LOOKUP[_clean_str(canonical_name)] = canonical_name
    # Canonical Arabic
    _NORMALIZED_LOOKUP[_clean_str(entry.canonical_name_ar)] = canonical_name
    # Scientific name
    _NORMALIZED_LOOKUP[_clean_str(entry.scientific_name)] = canonical_name
    # Aliases
    for alias in entry.aliases:
        _NORMALIZED_LOOKUP[_clean_str(alias)] = canonical_name

# Add common generic fallback resolutions
