    opt_min_temp: float = 18.0
    opt_max_temp: float = 30.0
    max_temp: float = 38.0
    crop_cycle_min_days: int = 90
    crop_cycle_max_days: int = 120

    # Economics benchmarks (per feddan)
    default_expected_yield: float = 5.0
    default_price: float = 10000.0
    default_production_cost: float = 8000.0


