    """Canonical metadata and parameters for a recognized agricultural crop."""

    canonical_name_en: str
    canonical_name_ar: str
    scientific_name: str
    crop_family: str
    category: str  # Cereal, Legume, Vegetable, Fruit, Fiber, Oilseed, Forage, Sugar, Medicinal/Aromatic
    is_perennial: bool
    allowed_seasons: List[str]
    ecocrop_species: str
    water_key: str
    is_water_proxy: bool = False
    water_proxy_reference: Optional[str] = None
    aliases: List[str] = field(default_factory=list)

    # EcoCrop soil & climate tolerances
    min_ph: float = 6.0
    opt_min_ph: float = 6.5
    opt_max_ph: float = 7.5
    max_ph: float = 8.5
    max_ec: float = 2.5
    suitable_textures: List[str] = field(default_factory=lambda: ["Loam", "Clay", "Silt", "Sandy Loam"])
